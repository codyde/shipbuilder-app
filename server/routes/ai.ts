aiRoutes.post('/create-mvp-project', async (req: any, res: any) => {
  let userId: string | undefined;
  let userProvider: AIProvider = 'anthropic';
  let statusStreamer: StatusStreamer | null = null;
  let mvpPlan: MVPPlanPayload;

  try {
    const rawPlan = req.body.mvpPlan as MVPPlanPayload | undefined;
    if (!rawPlan) {
      return res.status(400).json({ error: 'MVP plan is required' });
    }

    if (!Array.isArray(rawPlan.tasks) || rawPlan.tasks.length === 0) {
      return res.status(400).json({ error: 'MVP plan must include at least one task' });
    }

    mvpPlan = {
      ...rawPlan,
      tasks: rawPlan.tasks
    };

    userId = req.user?.id;
    if (!userId) {
      return res.status(401).json({ error: 'User not authenticated' });
    }

    const user = await databaseService.getUserById(userId);
    userProvider = user?.aiProvider === 'openai' ? 'openai' : 'anthropic';

    console.log(`

🎆 [35m[MVP_CREATE][0m Starting MVP creation
   📝 Project: [33m${mvpPlan.projectName}[0m
   🗺️ Tasks: [36m${mvpPlan.tasks.length}[0m
   ⚙️ Execution: [32mDeterministic server flow[0m
`);
    logger.info('Starting MVP creation (deterministic flow)', {
      userId,
      provider: userProvider,
      projectName: mvpPlan.projectName,
      taskCount: mvpPlan.tasks.length
    });

    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Transfer-Encoding', 'chunked');
    res.setHeader('Cache-Control', 'no-cache');
    res.setHeader('Connection', 'keep-alive');

    statusStreamer = StatusStreamer.createWrapper(res, {
      userId,
      provider: userProvider || 'unknown',
      operation: 'create_mvp_project',
      projectName: mvpPlan.projectName,
      taskCount: mvpPlan.tasks.length
    }, false);

    statusStreamer.sendProgressUpdate(`🚀 Starting MVP creation for "${mvpPlan.projectName}" with ${mvpPlan.tasks.length} tasks`);

    const { createTaskTools } = await import('../tools/task-tools.js');
    const taskTools = createTaskTools(userId);
    const wrappedTools = wrapToolsWithStatus({
      createProject: taskTools.createProject,
      createTask: taskTools.createTask
    }, statusStreamer);

    (globalThis as any).mvpTaskCount = mvpPlan.tasks.length;

    const projectDescription = buildProjectDescription(mvpPlan);
    const projectResult = await wrappedTools.createProject.execute({
      name: mvpPlan.projectName,
      description: projectDescription
    });

    if (!projectResult?.success || !projectResult.data?.id) {
      throw new Error(projectResult?.message || 'Failed to create project');
    }

    const projectId = projectResult.data.id;
    let createdTasks = 0;

    for (const task of mvpPlan.tasks) {
      const taskResult = await wrappedTools.createTask.execute({
        projectId,
        title: task.title,
        description: task.description,
        priority: normalizePriority(task.priority)
      });

      if (taskResult?.success === false) {
        throw new Error(taskResult?.message || `Failed to create task "${task?.title || 'unknown'}"`);
      }

      createdTasks += 1;
      statusStreamer.sendProgressUpdate(`Progress: ${createdTasks}/${mvpPlan.tasks.length} tasks created`);
    }

    statusStreamer.sendCompletion(`🎉 MVP "${mvpPlan.projectName}" created successfully with ${mvpPlan.tasks.length} tasks!`);
    console.log(`
✨ [32m[MVP_CREATE][0m Completed deterministic flow for project: [33m${mvpPlan.projectName}[0m
${'='.repeat(60)}
`);
    logger.info('MVP creation completed (deterministic flow)', {
      userId,
      provider: userProvider,
      projectId,
      projectName: mvpPlan.projectName,
      taskCount: mvpPlan.tasks.length
    });
  } catch (error) {
    console.error(`
🚨 [31m[MVP_CREATE][0m Error during MVP creation:`, error);
    logger.error('MVP creation failed (deterministic flow)', {
      userId: userId || 'unknown',
      provider: userProvider,
      projectName: mvpPlan?.projectName,
      taskCount: mvpPlan?.tasks?.length,
      error: error instanceof Error ? error.message : 'Unknown error'
    });

    if (statusStreamer) {
      const errorMessage = error instanceof Error ? error.message : 'Failed to create MVP project.';
      statusStreamer.sendStatus({
        type: 'tool-error',
        status: 'error',
        message: `❌ MVP creation failed: ${errorMessage}`,
        data: { error: errorMessage }
      });
    } else if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to create MVP project' });
    }
  } finally {
    statusStreamer?.close();
  }
});
