const { logger } = Sentry;

const PRIORITY_LOW = 'low';
const PRIORITY_MEDIUM = 'medium';
const PRIORITY_HIGH = 'high';
const VALID_PRIORITIES = new Set<string>([PRIORITY_LOW, PRIORITY_MEDIUM, PRIORITY_HIGH]);

interface MVPTaskPayload {
  title: string;
  description?: string;
  priority?: string;
}

interface MVPTechStackPayload {
  frontend?: string;
  backend?: string;
  database?: string;
  hosting?: string;
}

interface MVPPlanPayload {
  projectName: string;
  description?: string;
  features?: string[];
  techStack?: MVPTechStackPayload;
  tasks: MVPTaskPayload[];
}

function normalizePriority(priority?: string): 'low' | 'medium' | 'high' {
  if (!priority || typeof priority !== 'string') {
    return PRIORITY_MEDIUM;
  }

  const normalized = priority.toLowerCase().trim();
  if (VALID_PRIORITIES.has(normalized)) {
    return normalized as 'low' | 'medium' | 'high';
  }

  if (normalized.includes('high')) {
    return PRIORITY_HIGH;
  }
  if (normalized.includes('low')) {
    return PRIORITY_LOW;
  }
  return PRIORITY_MEDIUM;
}

function buildProjectDescription(plan: MVPPlanPayload): string {
  const sections: string[] = [];

  if (plan.description) {
    sections.push(plan.description.trim());
  }

  const techStackParts: string[] = [];
  if (plan.techStack?.frontend) techStackParts.push(`Frontend: ${plan.techStack.frontend}`);
  if (plan.techStack?.backend) techStackParts.push(`Backend: ${plan.techStack.backend}`);
  if (plan.techStack?.database) techStackParts.push(`Database: ${plan.techStack.database}`);
  if (plan.techStack?.hosting) techStackParts.push(`Hosting: ${plan.techStack.hosting}`);

  if (techStackParts.length) {
    sections.push(`Tech Stack:\n- ${techStackParts.join('\n- ')}`);
  }

  if (Array.isArray(plan.features) && plan.features.length > 0) {
    const featureList = plan.features.map((feature) => `- ${feature}`).join('\n');
  sections.push(`Core Features:\n${featureList}`);
  }

  if (Array.isArray(plan.tasks) && plan.tasks.length > 0) {
    const previewTasks = plan.tasks.slice(0, 5).map((task: MVPTaskPayload, index: number) => {
      const priority = normalizePriority(task.priority);
      return `${index + 1}. ${task.title} (${priority}) - ${task.description || 'No description provided'}`;
    }).join('\n');
    sections.push(`Initial Tasks Preview:\n${previewTasks}${plan.tasks.length > 5 ? '\n...and more tasks generated by the MVP builder.' : ''}`);
  }

  return sections.join('\n\n');
}

export const aiRoutes = express.Router();

aiRoutes.post('/generate-details', async (req: any, res: any) => {
  // Declare variables at function scope so they're accessible in catch blocks
  let userId: string | undefined;
  
  try {
    const { prompt, context } = req.body;
    
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    // Get authenticated user ID
    userId = req.user?.id;
    if (!userId) {
      return res.status(401).json({ error: 'User not authenticated' });
    }

    // Get the appropriate AI model
    let model;
    try {
      model = await AIProviderService.getModel(userId);
    } catch (error) {
      return res.status(500).json({ 
        error: error instanceof Error ? error.message : 'Failed to get AI model' 
      });
    }

    const systemPrompt = `You are a senior technical lead helping to generate detailed implementation plans and build processes for development tasks.

Context:
- Task Title: ${context?.title || 'Not provided'}
- Task Description: ${context?.description || 'Not provided'}
- Task Priority: ${context?.priority || 'Not provided'}

Generate a comprehensive build process and implementation details for this task. Focus on creating an actionable step-by-step implementation guide that a developer can follow. Your response should include:

## Implementation Details
- Step-by-step build process
- Technical approach and architecture decisions
- Code structure and file organization
- Key components/modules needed

## Acceptance Criteria
- Clear definition of "done" for this task
- Testable requirements
- Expected functionality and behavior

## Technical Requirements
- Dependencies and libraries needed
- Configuration requirements
- Environment setup needs
- Database schema changes (if applicable)

Format your response in markdown with clear sections and actionable steps. Be specific about implementation details while keeping it practical and achievable.`;

    // Set headers for streaming
    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Transfer-Encoding', 'chunked');
    res.setHeader('Cache-Control', 'no-cache');
    res.setHeader('Connection', 'keep-alive');

    const result = streamText({
      model,
      experimental_telemetry: {
        isEnabled: true,
        functionId: "generate-details"
      },
      system: systemPrompt,
      onError: (error) => {
        console.error('AI generation error:', error);
      },
      prompt: prompt,
      // Removed maxTokens - not supported by responses API
    });

    // Stream the text chunks to the client
    for await (const chunk of result.textStream) {
      res.write(chunk);
    }

    res.end();
  } catch (error) {
    console.error('AI generation error:', error);
    if (!res.headersSent) {
      res.status(500).json({ error: 'Failed to generate details' });
    } else {
      res.end();
    }
  }
});


